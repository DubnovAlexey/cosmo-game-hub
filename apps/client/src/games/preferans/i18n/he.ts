const by = <T>(seat: Seat, you: T, he: T, she: T): T => (seat === 0 ? you : seat === 1 ? he : she);
const name = (seat: Seat): string => NAMES[seat];

const closed = (reason: ClosedReason): string => {
    switch (reason.kind) {
        case 'notReady': return 'בקרוב: המנוע עוד לא משחק את זה.';
        case 'conflict': return `אי אפשר לשלב עם "${OPTIONS[reason.with].name}". כבו אותה קודם.`;
        case 'requires': return `צריך קודם להפעיל את "${OPTIONS[reason.option].name}".`;
        case 'variant': return `רק בגרסאות: ${reason.variants.map(variant => VARIANTS[variant].name).join(', ')}.`;
        case 'players': return `רק עם ${reason.players.join(' או ')} שחקנים.`;
        default: return '';
    }
};

