const RANKS = ['Семёрка', 'Восьмёрка', 'Девятка', 'Десятка', 'Валет', 'Дама', 'Король', 'Туз'];
const SUITS = ['пик', 'треф', 'бубен', 'червей'];
const tricksWord = (count: number): string => {
    const last = count % 10;
    const lastTwo = count % 100;
    if (last === 1 && lastTwo !== 11) return 'взятка';
    if (last >= 2 && last <= 4 && (lastTwo < 12 || lastTwo > 14)) return 'взятки';
    return 'взяток';
};

// [EN] Who sits where, in the forms the sentences need: you (polite «вы»), Orion (he), Vega (she).
// [RU] Кто где сидит, в формах, которые нужны фразам: вы, Орион (он), Вега (она).
const NAMES = ['Вы', 'Орион', 'Вега'] as const;
const TO = ['Вам', 'Ориону', 'Веге'] as const;
const FOR = ['себя', 'Ориона', 'Вегу'] as const;
const by = <T>(seat: Seat, you: T, he: T, she: T): T => (seat === 0 ? you : seat === 1 ? he : she);
const name = (seat: Seat): string => NAMES[seat];

const closed = (reason: ClosedReason): string => {
    switch (reason.kind) {
        case 'notReady': return 'Скоро: движок ещё этого не умеет.';
        case 'conflict': return `Нельзя вместе с «${OPTIONS[reason.with].name}». Сначала снимите её.`;
        case 'requires': return `Сначала нужно включить «${OPTIONS[reason.option].name}».`;
        case 'variant': return `Только в вариантах: ${reason.variants.map(variant => VARIANTS[variant].name).join(', ')}.`;
        case 'players': return `Только для ${reason.players.join(' или ')} игроков.`;
        default: return '';
    }
};

